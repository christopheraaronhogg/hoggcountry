#!/usr/bin/env node
// Extraction loop: turn the AWOL "The A.T. Guide" water-source FACTS
// (src/data/at-water-sources.json — location/name/type/off-trail only, no AWOL
// prose) into a Scout-consumable, cited water reference on OUR mile frame with
// OUR wording. Reliability is OUR cite-and-verify derivation from the source
// type, NOT AWOL's rating. License posture: facts are free (Feist); we add our
// own selection framing, wording, and structure, and cite AWOL. AWOL has no
// EULA/contract layer. See docs/trail-data-provenance.md §2.
//
//   node scripts/build-scout-awol-water.mjs
//
// Writes apps/openclaw-web/src/lib/server/generated/awol-water-reference.ts,
// which the public mobile field pack imports to enrich Scout's water layer.
// Re-run after a new AWOL extraction (npm run awol:build-water).

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const INPUT = path.join(repoRoot, 'src/data/at-water-sources.json');
const OUTPUT = path.join(repoRoot, 'apps/openclaw-web/src/lib/server/generated/awol-water-reference.ts');

const TOTAL_AT_MILES = 2197.9;

// Same AT state frame Scout uses (scout-official-sources AT_STATE_MILE_RANGES).
const AT_STATE_MILE_RANGES = [
  ['GA', 0, 78.6], ['NC', 78.6, 167.5], ['TN', 167.5, 470.0], ['VA', 470.0, 1008.0],
  ['WV', 1008.0, 1025.0], ['MD', 1025.0, 1067.0], ['PA', 1067.0, 1296.0], ['NJ', 1296.0, 1369.0],
  ['NY', 1369.0, 1456.0], ['CT', 1456.0, 1508.0], ['MA', 1508.0, 1602.0], ['VT', 1602.0, 1751.0],
  ['NH', 1751.0, 1918.0], ['ME', 1918.0, 2200.0]
];

function stateForMile(mile) {
  return AT_STATE_MILE_RANGES.find(([, lo, hi]) => mile >= lo && mile < hi)?.[0] ?? null;
}

// OUR cite-and-verify reliability derivation from the source TYPE (AWOL gives no
// per-source rating). Deliberately conservative — a named source is "real but
// confirm flow" (seasonal), never auto-promoted to a guaranteed source. The
// honest detail lives in the note, not an invented rating.
function reliabilityForType(type) {
  switch (type) {
    case 'town':
    case 'piped':
      return 'reliable'; // town taps / piped springs are the most dependable
    case 'spring':
    case 'river':
      return 'seasonal'; // real source, confirm current flow
    case 'stream':
    default:
      return 'thin'; // least dependable; treat as a candidate until confirmed
  }
}

function round1(value) {
  return Math.round(value * 10) / 10;
}

const raw = JSON.parse(readFileSync(INPUT, 'utf8'));
if (!Array.isArray(raw)) throw new Error(`${INPUT} is not an array`);

const sources = [];
const problems = [];
for (const entry of raw) {
  const mile = Number(entry.mile);
  const name = String(entry.name ?? '').trim();
  const type = String(entry.type ?? '').trim() || 'stream';
  const offTrail = Number(entry.offTrail ?? 0);
  if (!Number.isFinite(mile) || mile < 0 || mile > TOTAL_AT_MILES) {
    problems.push(`out-of-range mile: ${JSON.stringify(entry)}`);
    continue;
  }
  if (!name) {
    problems.push(`missing name: ${JSON.stringify(entry)}`);
    continue;
  }
  const offTrailMiles = Number.isFinite(offTrail) && offTrail > 0 ? round1(offTrail) : 0;
  const reliability = reliabilityForType(type);
  const offNote = offTrailMiles > 0 ? `, ${offTrailMiles.toFixed(1)} mi off trail` : '';
  // OUR wording — never AWOL's prose.
  const note = `AWOL-listed ${type}${offNote}. Real water source; confirm current flow before relying on it.`;
  sources.push({ mile: round1(mile), name, type, offTrailMiles, reliability, state: stateForMile(mile), note });
}

sources.sort((a, b) => a.mile - b.mile);

if (problems.length) {
  console.warn(`build-scout-awol-water: skipped ${problems.length} bad rows`); // eslint-disable-line no-console
  for (const problem of problems.slice(0, 10)) console.warn('  - ' + problem); // eslint-disable-line no-console
}
if (sources.length < 100) {
  throw new Error(`Only ${sources.length} valid AWOL water sources — refusing to write a thin reference.`);
}

const generatedAt = new Date().toISOString();
const citation =
  'The A.T. Guide (AWOL), David Miller — water-source location/mile/type facts, cited. ' +
  'Reliability is Hogg Country\'s cite-and-verify derivation from source type, not an AWOL rating.';

const banner = `// GENERATED by scripts/build-scout-awol-water.mjs — do not edit by hand.
// AWOL "The A.T. Guide" water-source FACTS re-expressed on our frame, our wording,
// cited. Reliability is OUR cite-and-verify derivation from type, NOT AWOL's.
// Re-run the generator after a fresh extraction. See docs/trail-data-provenance.md §2.
`;

const body = `${banner}
export interface AwolWaterSource {
\treadonly mile: number;
\treadonly name: string;
\treadonly type: string;
\treadonly offTrailMiles: number;
\treadonly reliability: 'reliable' | 'seasonal' | 'thin';
\treadonly state: string | null;
\treadonly note: string;
}

export const AWOL_WATER_GENERATED_AT = ${JSON.stringify(generatedAt)};
export const AWOL_WATER_CITATION = ${JSON.stringify(citation)};

export const AWOL_WATER_SOURCES: readonly AwolWaterSource[] = ${JSON.stringify(sources, null, 1)};
`;

mkdirSync(path.dirname(OUTPUT), { recursive: true });
writeFileSync(OUTPUT, body, 'utf8');
console.log(`build-scout-awol-water: wrote ${sources.length} cited water sources → ${path.relative(repoRoot, OUTPUT)}`); // eslint-disable-line no-console
